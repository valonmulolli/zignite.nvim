---@type table
local M = {}

---@param value string
---@return string
function M.trim_text(value)
	if type(value) ~= "string" then
		return ""
	end
	return (value:gsub("^%s+", ""):gsub("%s+$", ""))
end

---@param lines string[]|nil
---@return boolean
function M.is_cmake_generated_makefile_lines(lines)
	for _, raw_line in ipairs(lines or {}) do
		local line = tostring(raw_line or "")
		if line:find("CMAKE generated file: DO NOT EDIT!", 1, true) then
			return true
		end
		if line:find('Generated by "Unix Makefiles" Generator', 1, true) then
			return true
		end
	end
	return false
end

---@param text string
---@return string
function M.normalize_path_text(text)
	if type(text) ~= "string" then
		return ""
	end
	return vim.fs.normalize(text):gsub("\\", "/")
end

---@param text string
---@return string
function M.escape_lua_pattern(text)
	return tostring(text or ""):gsub("([^%w])", "%%%1")
end

---@param root string
---@param filepath string
---@return string
function M.make_relative_to_root(root, filepath)
	local root_norm = M.normalize_path_text(root)
	local file_norm = M.normalize_path_text(filepath)
	if root_norm ~= "" and file_norm:sub(1, #root_norm + 1) == (root_norm .. "/") then
		return file_norm:sub(#root_norm + 2)
	end
	return vim.fn.fnamemodify(filepath, ":t")
end

---@param line string
---@return string
function M.strip_hash_comment(line)
	return tostring(line or ""):gsub("#.*$", "")
end

---@param text string
---@return string[]
function M.tokenize_cmake_args(text)
	---@type string[]
	local tokens = {}
	for token in tostring(text or ""):gmatch("%S+") do
		local cleaned = token:gsub('^"', ""):gsub('"$', "")
		cleaned = cleaned:gsub("^'", ""):gsub("'$", "")
		if cleaned ~= "" then
			tokens[#tokens + 1] = cleaned
		end
	end
	return tokens
end

---@param text string
---@return string[]
function M.tokenize_quoted_args(text)
	---@type string[]
	local tokens = {}
	local source = tostring(text or "")
	local index = 1
	local length = #source
	while index <= length do
		local quote = source:sub(index, index)
		if quote == "'" or quote == '"' then
			local close_index = index + 1
			while close_index <= length and source:sub(close_index, close_index) ~= quote do
				close_index = close_index + 1
			end
			if close_index <= length then
				local token = source:sub(index + 1, close_index - 1)
				if token ~= "" then
					tokens[#tokens + 1] = token
				end
				index = close_index
			end
		end
		index = index + 1
	end
	return tokens
end

---@param payload string
---@return table<string, string|number|boolean|table|nil>|nil
function M.decode_json_payload(payload)
	if type(payload) ~= "string" or payload == "" then
		return nil
	end
	if vim.json and type(vim.json.decode) == "function" then
		local ok, decoded = pcall(vim.json.decode, payload)
		if ok then
			return decoded
		end
	end
	if vim.fn and type(vim.fn.json_decode) == "function" then
		local ok, decoded = pcall(vim.fn.json_decode, payload)
		if ok then
			return decoded
		end
	end
	return nil
end

---@param lines string[]|nil
---@return table<string, string>
function M.parse_makefile_targets(lines)
	---@type table<string, string>
	local commands = {}
	for _, raw_line in ipairs(lines or {}) do
		local line = tostring(raw_line or "")
		if line:match("^%s*$") or line:match("^%s*#") then
			goto continue
		end
		if line:match("^\t") then
			goto continue
		end
		if line:match("^%s*[%w%._%-]+%s*[:+?]?=") then
			goto continue
		end
		local target_segment = line:match("^%s*([^:]+)%s*:")
		if not target_segment then
			goto continue
		end
		for raw_target in target_segment:gmatch("%S+") do
			local target = M.trim_text(raw_target)
			if
				target ~= ""
				and target ~= "|"
				and not target:match("^%.")
				and not target:find("%%", 1, true)
				and not target:find("%$%(", 1, true)
			then
				commands[target] = "make " .. target
			end
		end
		::continue::
	end
	return commands
end

return M
